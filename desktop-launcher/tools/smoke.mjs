// Run with Electron, not Node. Uses an isolated temporary profile.
import { app, BrowserWindow } from "electron";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import assert from "node:assert/strict";
import { setTimeout as delay } from "node:timers/promises";
import "../src/main.js";

const profile = fs.mkdtempSync(path.join(os.tmpdir(), "desktop-launcher-smoke-"));
app.setPath("userData", profile);
let timeout = setTimeout(() => { console.error("Smoke test timed out"); app.exit(1); }, 25000);
app.whenReady().then(async () => {
  await delay(1200);
  const launcher = BrowserWindow.getAllWindows().find((win) => win.webContents.getURL().endsWith("launcher.html"));
  assert.ok(launcher, "Launcher window loads");
  const evaluate = (script) => launcher.webContents.executeJavaScript(script, true);
  const result = await evaluate("window.desktopLauncher.listApps()");
  assert.equal(result.ok, true, JSON.stringify(result));
  assert.ok(result.apps.some((entry) => entry.id === "sip"));
  assert.equal(await evaluate("document.querySelectorAll('.app-row').length"), result.apps.length);
  const opened = await evaluate("Promise.all([desktopLauncher.openApp('sip'), desktopLauncher.openApp('sip'), desktopLauncher.openApp('sip')])");
  assert.ok(opened.every((item) => item.ok), JSON.stringify(opened));
  let sip = BrowserWindow.getAllWindows().find((win) => win.webContents.getURL() === "app://local/sip.html");
  assert.ok(sip);
  assert.equal(BrowserWindow.getAllWindows().length, 2);
  assert.equal(sip.isAlwaysOnTop(), true);
  const sipEval = (script) => sip.webContents.executeJavaScript(script, true);
  assert.equal(await sipEval("typeof require + ':' + typeof desktopLauncher"), "undefined:undefined");
  assert.equal(await sipEval("document.querySelector('h1').textContent"), "Sip");
  const before = await sipEval("document.getElementById('time').textContent");
  await delay(1300);
  assert.notEqual(await sipEval("document.getElementById('time').textContent"), before);
  await sipEval("document.getElementById('mins').value = '15'; document.getElementById('mins').dispatchEvent(new Event('change')); void 0");
  const stored = await sipEval("JSON.parse(localStorage.getItem('sip'))");
  assert.equal(stored.mins, "15");
  await sipEval("document.getElementById('drank').click(); void 0");
  assert.ok((await sipEval("JSON.parse(localStorage.getItem('sip')).due")) >= stored.due);
  await evaluate("desktopLauncher.toggleAlwaysOnTop('sip')");
  assert.equal(sip.isAlwaysOnTop(), false);
  await evaluate("desktopLauncher.showHideApp('sip')"); assert.equal(sip.isVisible(), false);
  await evaluate("desktopLauncher.showHideApp('sip')"); assert.equal(sip.isVisible(), true);
  const screenshotDir = new URL("../dist/smoke/", import.meta.url);
  fs.mkdirSync(screenshotDir, { recursive: true });
  fs.writeFileSync(new URL("launcher.png", screenshotDir), (await launcher.webContents.capturePage()).toPNG());
  fs.writeFileSync(new URL("sip.png", screenshotDir), (await sip.webContents.capturePage()).toPNG());
  sip.setBounds({ x: 100, y: 100, width: 420, height: 600 });
  await delay(150);
  sip.close();
  await delay(150);
  assert.equal(BrowserWindow.getAllWindows().length, 1);
  const reopened = await evaluate("desktopLauncher.openApp('sip')");
  assert.equal(reopened.ok, true, JSON.stringify(reopened));
  sip = BrowserWindow.getAllWindows().find((win) => win.webContents.getURL() === "app://local/sip.html");
  assert.equal(sip.isAlwaysOnTop(), false);
  assert.equal(sip.getBounds().width, 420);
  assert.equal(await sipEval("document.getElementById('mins').value"), "15");
  // Emit the real Electron event against the production listener without networking.
  let blocked = false;
  sip.webContents.emit("will-navigate", { preventDefault: () => { blocked = true; } }, "https://example.com");
  assert.equal(blocked, true);
  launcher.close();
  assert.equal(launcher.isDestroyed(), false);
  assert.equal(launcher.isVisible(), false);
  app.emit("second-instance");
  assert.equal(launcher.isVisible(), true);
  await delay(350);
  assert.equal(JSON.parse(fs.readFileSync(path.join(profile, "window-state.json"))).apps.sip.alwaysOnTop, false);
  console.log("PASS: real Electron launcher bridge, registry, isolated Sip renderer, countdown, interval/reset/storage, duplicate opens, pin toggle, show/hide, bounds restore, close/reopen, launcher hide, second-instance handler, navigation guard, and persisted state.");
  console.log(`Screenshots: ${screenshotDir.pathname}`);
  clearTimeout(timeout);
  app.quit();
}).catch((error) => {
  console.error(error); clearTimeout(timeout); app.exit(1);
});
